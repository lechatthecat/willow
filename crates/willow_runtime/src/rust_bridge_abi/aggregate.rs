//! Synchronous aggregate transport. Frames own stable collector-rewritable slots.
use crate::{array, gc, string};
use willow_abi::ffi::{WillowBridgeValue, WillowSliceU8};
use willow_abi::{EnumVariantLayout, SlotKind};

#[cfg(test)]
const INPUT_COPIES: crate::observation::Counter =
    crate::observation::Counter(crate::observation::Event::InputCopies);
#[cfg(test)]
const OUTPUT_COPIES: crate::observation::Counter =
    crate::observation::Counter(crate::observation::Event::OutputCopies);

#[derive(Default)]
struct Frame {
    // The synchronous bridge returns raw values and borrowed String data to
    // foreign code. Keep their addresses fixed until the bridge frame ends.
    roots: Vec<gc::PinLease<gc::ForeignReference>>,
    addresses: crate::id_hash::IdSet<u64>,
}

#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub extern "C" fn willow_rust_bridge_frame_new() -> *mut u8 {
    Box::into_raw(Box::<Frame>::default()).cast()
}

/// # Safety
/// Transfer the non-null original allocation from willow_rust_bridge_frame_new exactly once,
/// after all frame accesses and borrows of pinned data have ended.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_frame_drop(frame: *mut u8) {
    // SAFETY: The opaque pointer comes from Box<Frame>, with that type's alignment. The
    // synchronous caller owns it until frame_drop.
    unsafe { drop(Box::from_raw(frame.cast::<Frame>())) }
}

/// # Safety
/// The caller must hold exclusive access to a live bridge frame from
/// willow_rust_bridge_frame_new. A nonzero object must be a current live managed payload
/// that the frame may pin.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_root(frame: *mut u8, object: u64) {
    if object == 0 {
        return;
    }
    // SAFETY: The opaque pointer comes from Box<Frame>, with that type's alignment. The
    // synchronous caller owns it until frame_drop.
    let frame = unsafe { &mut *frame.cast::<Frame>() };
    if frame.addresses.insert(object) {
        frame.roots.push(gc::PinLease::new(object as *mut u8));
    }
}

/// # Safety
/// The caller must supply a writable, aligned output slot disjoint from the
/// string. A nonzero object must be a live WillowString pinned by the bridge
/// frame until the returned bytes are no longer borrowed.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_string_data(object: u64, out: *mut WillowSliceU8) {
    let object = object as *const u8;
    // SAFETY: The bridge caller pins this string for the borrow; null denotes an empty string.
    let len = unsafe { string::willow_string_len(object) } as usize;
    // The bridge frame pins the string until foreign code releases the borrow.
    let ptr = if object.is_null() {
        std::ptr::NonNull::<u8>::dangling().as_ptr()
    } else {
        // SAFETY: The frame keeps the live string or buffer stable. Its byte count bounds this
        // borrowed data range.
        unsafe { object.add(willow_abi::string_layout::DATA_OFFSET) }
    };
    // SAFETY: The ABI caller provides a live, aligned, writable output slot for this result.
    unsafe {
        *out = WillowSliceU8 { ptr, len };
    }
}

/// # Safety
/// The caller keeps the current array handle live and stable throughout the call.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_bytes_len(object: u64) -> usize {
    // SAFETY: The bridge caller supplies the current live array handle.
    (unsafe { array::array_len(object as *mut u8) }) as usize
}

/// # Safety
/// The caller keeps the current Array<u8> live and stable throughout the call.
/// For nonzero len, out must cover that many exclusive writable bytes disjoint from the input.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_bytes_copy(object: u64, out: *mut u8, len: usize) {
    // SAFETY: The caller keeps this packed byte array live throughout the copy.
    if len != unsafe { willow_rust_bridge_bytes_len(object) } {
        crate::failure::fatal_invariant("rust_bridge_bytes_length");
    }
    if len != 0 {
        // SAFETY: the generated byte adapter supplies a live packed Array<u8>. It copies the
        // input synchronously before calling user code. No array mutation or GC safepoint
        // occurs between borrowing the backing bytes and finishing the copy.
        let bytes = unsafe { array::packed_bytes(object as *mut u8) };
        // SAFETY: len matches the source length. The caller reserves at least len writable
        // bytes in a separate native Vec, so the two ranges do not overlap.
        unsafe { std::ptr::copy_nonoverlapping(bytes.as_ptr(), out, len) };
        crate::observation::record(crate::observation::Event::InputCopies, 1);
    }
}

/// # Safety
/// The caller owns a live bridge frame exclusively for this operation. For
/// nonzero length the input must cover that many initialized native bytes in one
/// allocation and remain readable and unmodified through the synchronous copy.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_buffer(
    frame: *mut u8,
    bytes: *const u8,
    len: usize,
    is_string: u32,
) -> u64 {
    let Ok(length) = i64::try_from(len) else {
        crate::failure::fatal_invariant("rust_bridge_buffer_length");
    };
    let object = if is_string != 0 {
        // SAFETY: The bridge caller keeps the supplied native byte range readable through this
        // copy.
        unsafe { string::willow_string_alloc(bytes, length) }
    } else {
        let bytes = if len == 0 {
            &[]
        } else {
            // SAFETY: the bridge passes the pointer and length of a native byte slice and
            // keeps its backing storage readable until from_native_bytes finishes copying.
            unsafe { std::slice::from_raw_parts(bytes, len) }
        };
        array::from_native_bytes(bytes)
    };
    // SAFETY: The adapter retains exclusive ownership of the frame and passes the current
    // payload for pinning.
    unsafe { willow_rust_bridge_root(frame, object as u64) };
    object as u64
}

/// # Safety
/// The object must be a live, stable word-aligned enum with an initialized readable tag.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_tag(object: u64) -> u64 {
    // SAFETY: The GC word-aligns the enum or record payload. Its generated layout reserves the
    // tag, descriptor or field words addressed here.
    unsafe { *(object as *const u64) }
}

/// # Safety
/// Supply a disjoint, aligned, writable WillowBridgeValue output for the call. The object
/// must be a live, stable word-aligned enum with an initialized active payload of one word,
/// or two if pair is nonzero.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_payload(
    object: u64,
    pair: u32,
    out: *mut WillowBridgeValue,
) {
    let layout = EnumVariantLayout::new(0, &[]);
    // SAFETY: the GC word-aligns the live enum. The variant layout places its initialized
    // payload at this whole-word offset after the tag.
    let payload = unsafe {
        (object as *const u8)
            .add(layout.payload_byte_offset(8) as usize)
            .cast::<u64>()
    };
    // SAFETY: the generated decoder derives pair from the selected payload's layout. A pair
    // has two initialized words at payload, and a single-word payload needs only the first.
    // The caller supplies a separate, aligned, writable WillowBridgeValue for the result.
    unsafe {
        *out = WillowBridgeValue {
            low: *payload,
            high: if pair != 0 { *payload.add(1) } else { 0 },
        };
    }
}

/// # Safety
/// The caller must hold exclusive access to a live bridge frame from
/// willow_rust_bridge_frame_new. Supply a readable, aligned, fully initialized
/// WillowBridgeValue. The pair and reference flags must match the declared slot kind. A
/// reference low word must be null or the current address of a live object of that type.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_enum(
    frame: *mut u8,
    tag: u64,
    value: *const WillowBridgeValue,
    pair: u32,
    reference: u32,
) -> u64 {
    // SAFETY: The bridge caller supplies a readable, properly aligned WillowBridgeValue for this
    // call.
    let value = unsafe { *value };
    let kind = match (pair != 0, reference != 0) {
        (false, false) => SlotKind::Word,
        (false, true) => SlotKind::GcRef,
        (true, false) => SlotKind::ScalarPair,
        (true, true) => SlotKind::InterfacePair,
    };
    let slots = [kind];
    let layout = EnumVariantLayout::new(tag as u32, &slots);
    let referent = (reference != 0).then(|| gc::GcRootHandle::new(value.low as *mut u8));
    // SAFETY: The requested layout describes the initialized words of this object and its
    // type’s tracing or finalization contract.
    let object = unsafe {
        gc::willow_alloc_with_layout(
            gc::GcObjectKind::Enum,
            0,
            layout.payload_bytes(8) as i64,
            layout.gc_ref_mask(),
        )
    };
    let referent = referent
        .as_ref()
        .map_or(std::ptr::null_mut(), gc::GcRootHandle::load);
    // SAFETY: The adapter retains exclusive ownership of the frame and passes the current
    // payload for pinning.
    unsafe { willow_rust_bridge_root(frame, object as u64) };
    // SAFETY: allocation used this variant layout for the word-aligned object. Its payload
    // reserves two words when pair selected a pair slot kind and one word otherwise.
    unsafe {
        *object.cast::<u64>() = tag;
        let payload = object
            .add(layout.payload_byte_offset(8) as usize)
            .cast::<u64>();
        if reference != 0 {
            gc::willow_gc_write_barrier(
                object,
                std::ptr::null_mut(),
                referent,
                willow_abi::GcStoreDestination::EnumPayload as i64
                    | willow_abi::GC_STORE_OWNER_HAS_HEADER,
            );
            gc::store_gc_reference(payload.cast(), referent);
        } else {
            *payload = value.low;
        }
        if pair != 0 {
            *payload.add(1) = value.high;
        }
    }
    object as u64
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn aggregate_roundtrip_roots_and_linear_buffers() {
        const KEY: &str = "WILLOW_BRIDGE_AGGREGATE_CHILD";
        if std::env::var_os(KEY).is_none() {
            let output = std::process::Command::new(std::env::current_exe().unwrap())
                .args([
                    "--exact",
                    "rust_bridge_abi::aggregate::tests::aggregate_roundtrip_roots_and_linear_buffers",
                    "--nocapture",
                ])
                .env(KEY, "1")
                .output()
                .unwrap();
            assert!(
                output.status.success(),
                "{}",
                String::from_utf8_lossy(&output.stderr)
            );
            return;
        }
        let before = gc::runtime_root_count();
        let frame = willow_rust_bridge_frame_new();
        for len in [0, 1, 16, 256, 4096, 65536] {
            INPUT_COPIES.set(0);
            OUTPUT_COPIES.set(0);
            let bytes: Vec<u8> = (0..len).map(|index| index as u8).collect();
            // SAFETY: This test owns the frame and the input slice covers the supplied length
            // through the copy.
            let object = unsafe { willow_rust_bridge_buffer(frame, bytes.as_ptr(), len, 0) };
            // SAFETY: The bridge frame pins the Array<u8> constructed from bytes.
            assert_eq!(unsafe { willow_rust_bridge_bytes_len(object) }, len);
            gc::willow_gc_collect();
            let mut output = vec![0; len];
            // SAFETY: The frame pins the byte array and output owns len disjoint writable
            // bytes.
            unsafe { willow_rust_bridge_bytes_copy(object, output.as_mut_ptr(), len) };
            assert_eq!(output, bytes);
            assert_eq!(INPUT_COPIES.get(), usize::from(len != 0));
            assert_eq!(OUTPUT_COPIES.get(), usize::from(len != 0));
            eprintln!(
                "bytes length={len} input_copy={} output_copy={}",
                INPUT_COPIES.get(),
                OUTPUT_COPIES.get()
            );
        }
        for len in [0, 1, 16, 256, 4096] {
            INPUT_COPIES.set(0);
            OUTPUT_COPIES.set(0);
            // SAFETY: This fixture owns frame and requests ordinary word storage.
            let object = unsafe { willow_rust_bridge_array_new(frame, len, 0) };
            for i in 0..len {
                // SAFETY: The frame retains this word array; i selects one of its len slots.
                unsafe { willow_rust_bridge_array_set(object, i, (i as f64 - 0.5).to_bits()) };
            }
            for i in 0..len {
                assert_eq!(
                    // SAFETY: The frame retains the populated word array throughout these
                    // reads.
                    unsafe { willow_rust_bridge_array_get(object, i) },
                    (i as f64 - 0.5).to_bits()
                );
            }
            assert_eq!(INPUT_COPIES.get(), len);
            assert_eq!(OUTPUT_COPIES.get(), len);
            eprintln!("array elements={len} input={len} output={len}");
        }
        static DESCRIPTOR: u64 = 19;
        for len in [0usize, 1, 16, 64, 256] {
            let words = len + 1;
            let mut bitmap = vec![0u64; words.div_ceil(64) + 1];
            bitmap[0] = (bitmap.len() - 1) as u64;
            for i in 1..words {
                bitmap[1 + i / 64] |= 1 << (i % 64);
            }
            // Production wrappers use promoted static constants.
            let bitmap = Box::leak(bitmap.into_boxed_slice());
            // SAFETY: The fixture owns the frame. Static class and tracing descriptors
            // describe the allocated word count.
            let record = unsafe {
                willow_rust_bridge_record_new(
                    frame,
                    &DESCRIPTOR,
                    words,
                    bitmap.as_ptr(),
                    willow_abi::gc_bitmap_fingerprint(&bitmap[1..]),
                )
            };
            let child_frame = willow_rust_bridge_frame_new();
            // SAFETY: This test owns the frame and the input slice covers the supplied length
            // through the copy.
            let text =
                unsafe { willow_rust_bridge_buffer(child_frame, b"retained".as_ptr(), 8, 1) };
            INPUT_COPIES.set(0);
            OUTPUT_COPIES.set(0);
            for i in 0..len {
                // SAFETY: The fixture initializes the selected field of the pinned record
                // with the corresponding input and width.
                unsafe {
                    willow_rust_bridge_record_set(
                        record,
                        i + 1,
                        &WillowBridgeValue { low: text, high: 0 },
                        0,
                        1,
                    )
                };
            }
            // SAFETY: The fixture owns the original frame and has finished using every
            // borrowed payload.
            unsafe { willow_rust_bridge_frame_drop(child_frame) };
            gc::willow_gc_collect();
            for i in 0..len {
                let mut value = WillowBridgeValue::default();
                // SAFETY: The pinned record contains this initialized field at the supplied
                // word offset and width. Output is disjoint.
                unsafe { willow_rust_bridge_record_get(record, i + 1, 0, &mut value) };
                assert_eq!(value.low, text);
            }
            assert_eq!(INPUT_COPIES.get(), len);
            assert_eq!(OUTPUT_COPIES.get(), len);
            assert_eq!(
                // SAFETY: The GC word-aligns the enum or record payload. Its generated layout
                // reserves the tag, descriptor or field words addressed here.
                unsafe { *(record as *const *const u64) },
                &DESCRIPTOR as *const u64
            );
            eprintln!("record fields={len} input={len} output={len}");
        }
        for repeats in [0, 1, 16, 256, 4096] {
            let text = "é🙂".repeat(repeats);
            string::ALLOCATION_COPY_BYTES.set(0);
            // SAFETY: This test owns the frame and the input slice covers the supplied length
            // through the copy.
            let object = unsafe { willow_rust_bridge_buffer(frame, text.as_ptr(), text.len(), 1) };
            assert_eq!(string::ALLOCATION_COPY_BYTES.get(), text.len());
            let mut slice = WillowSliceU8 {
                ptr: std::ptr::null(),
                len: 0,
            };
            // SAFETY: This frame pins the string through the borrow and the output descriptor is a
            // local variable.
            unsafe { willow_rust_bridge_string_data(object, &mut slice) };
            assert_eq!(slice.len, text.len());
            assert_eq!(
                string::ALLOCATION_COPY_BYTES.get(),
                text.len(),
                "borrow copies zero bytes"
            );
            eprintln!(
                "string bytes={} output_copy={} input_copy=0",
                text.len(),
                string::ALLOCATION_COPY_BYTES.get()
            );
        }
        let text = "héllo 世界\0";
        // SAFETY: This test owns the frame and the input slice covers the supplied length through
        // the copy.
        let object = unsafe { willow_rust_bridge_buffer(frame, text.as_ptr(), text.len(), 1) };
        let collections = gc::willow_gc_major_collections();
        gc::willow_gc_collect();
        assert!(gc::willow_gc_major_collections() > collections);
        let mut slice = WillowSliceU8 {
            ptr: std::ptr::null(),
            len: 0,
        };
        // SAFETY: This frame pins the string through the borrow and the output descriptor is a
        // local variable.
        unsafe { willow_rust_bridge_string_data(object, &mut slice) };
        assert_eq!(
            // SAFETY: The frame keeps the live string or buffer stable. Its byte count bounds this
            // borrowed data range.
            unsafe { std::slice::from_raw_parts(slice.ptr, slice.len) },
            text.as_bytes()
        );
        for pair in [0, 1] {
            let value = WillowBridgeValue { low: 17, high: 29 };
            // SAFETY: The frame is exclusively owned here and the initialized input and flags
            // describe the selected variant.
            let object = unsafe { willow_rust_bridge_enum(frame, 1, &value, pair, 0) };
            let mut output = WillowBridgeValue::default();
            // SAFETY: The frame pins the enum built with this payload width and output is a
            // disjoint local value.
            unsafe { willow_rust_bridge_payload(object, pair, &mut output) };
            // SAFETY: The bridge frame pins this initialized enum and its tag.
            assert_eq!(unsafe { willow_rust_bridge_tag(object) }, 1);
            assert_eq!(output.low, 17);
            assert_eq!(output.high, if pair == 0 { 0 } else { 29 });
        }
        // SAFETY: The fixture owns the original frame and has finished using every borrowed
        // payload.
        unsafe { willow_rust_bridge_frame_drop(frame) };
        assert_eq!(gc::runtime_root_count(), before);
    }
}

/// # Safety
/// For nonzero len, bytes must point to len contiguous initialized bytes kept readable and
/// immutable through the call.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_panic_message(bytes: *const u8, len: usize) -> ! {
    let message = if len == 0 {
        "".into()
    } else {
        // SAFETY: The caller passes the pointer and byte length of one &str. Its panic payload
        // or static storage keeps all len bytes live and readable throughout this synchronous call.
        String::from_utf8_lossy(unsafe { std::slice::from_raw_parts(bytes, len) })
    };
    crate::failure::fatal_invariant(&format!("RustPanic: rust_bridge_panic: {message}"));
}

/// # Safety
/// The caller exclusively owns a live bridge frame for this operation. The reference flag must match the element layout.
#[unsafe(no_mangle)]
#[willow_runtime_macros::ffi_boundary]
pub unsafe extern "C" fn willow_rust_bridge_array_new(
    frame: *mut u8,
    len: usize,
    reference: u32,
) -> u64 {
    let length = i64::try_from(len)
        .unwrap_or_else(|_| crate::failure::fatal_invariant("rust_bridge_array_length"));
    let object = array::new_old_array(length, i64::from(reference)) as u64;
    // SAFETY: The adapter retains exclusive ownership of the frame and passes the current
    // payload for pinning.
    unsafe { willow_rust_bridge_root(frame, object) };
    object
}

